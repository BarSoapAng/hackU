    async def test_concurrent_enrollment_serializes_capacity_and_reuses_seat(self):
        rows, writes = [], []
        async def handler(request):
            await asyncio.sleep(0)
            if request.method == "POST":
                writes.append(1)
                rows.append(assignment())
                return httpx.Response(201, json=rows[0])
            return httpx.Response(200, json={"assignments": list(rows)})
        async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as client:
            photon = PhotonClient(client, "project", "test-secret")
            results = await asyncio.gather(photon.enroll("+14155550123", "one"), photon.enroll("+14155550123", "two"))
        assert results[0] == results[1] and len(writes) == 1

    async def test_assignment_pagination_does_not_miss_existing_participant(self):
        async def handler(request):
            if "pageToken" not in request.url.params:
                return httpx.Response(200, json={"assignments": [], "nextPageToken": "next"})
            return httpx.Response(200, json={"assignments": [assignment()]})
        async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as client:
            result = await PhotonClient(client, "project", "test-secret").enroll("+14155550123", "key")
        assert result.created_at == datetime.fromisoformat("2026-01-01T00:00:00+00:00").timestamp()
