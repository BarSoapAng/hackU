def event():
    def user(identifier, kind, phone):
        return {"id": identifier, "projectId": "project", "platform": "imessage", "kind": kind,
                "handle": phone, "details": {}, "metadata": {}}
    return {
        "id": "event-1", "type": "message.received", "apiVersion": "2026-07-01", "source": "imessage.photon",
        "timestamp": "2026-01-01T00:00:00Z", "data": {"projectId": "project", "object": {
            "id": "message-1", "projectId": "project", "platform": "imessage", "status": "received",
            "sentBy": user("human-1", "human", "+1 (415) 555-0123"),
            "receivedBy": user("agent-1", "agent", "+16283166196"),
            "space": {"id": "space-1", "kind": "direct", "participantIds": ["human-1", "agent-1"],
                      "platform": "imessage", "projectId": "project", "details": {}, "metadata": {}},
            "content": {"type": "text", "format": "plain", "text": "Hello 🌍"},
            "timestamps": {"receivedAt": "2026-01-01T00:00:00Z"},
        }},
    }


def signed(value, timestamp="1767225600"):
    raw = json.dumps(value, ensure_ascii=False).encode()
    signature = base64.b64encode(hmac.new(b"x" * 32, b"delivery-1." + timestamp.encode() + b"." + raw,
                                        hashlib.sha256).digest()).decode()
    return raw, {"webhook-id": "delivery-1", "webhook-timestamp": timestamp, "webhook-signature": "v1," + signature}


def verify(value, now=1767225600):
    return verify_event(*signed(value), "whsec_" + base64.b64encode(b"x" * 32).decode(), now, project_id="project")


def test_official_interoperability_signature_vector():
    # Independent vector published by Photon, not generated by the implementation.
    verify_signature('{"synthetic":true,"text":"Hello 🌍"}'.encode(), {
        "webhook-id": "synthetic-vector", "webhook-timestamp": "1767225600",
        "webhook-signature": "v1,0urZDpPAiQuH0H0rEB2NpIzgZKIhN6z++ZQqVUiN8e8=",
    }, "whsec_BwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwc=", 1767225600)


def test_raw_signature_unicode_and_delivery_identity():
    inbound = verify(event())
    assert inbound.phone == "+14155550123"
    assert inbound.destination == "+16283166196"
    assert inbound.event_id == "event-1"  # Durable event ID, not a redelivery's header ID.
    assert inbound.message_id == "message-1"
    assert inbound.space_id == "space-1" and inbound.agent_id == "agent-1"
    assert inbound.text == "Hello 🌍"
    raw, headers = signed(event())
    with pytest.raises(WebhookError, match="signature"):
        verify_event(raw + b" ", headers, "whsec_" + base64.b64encode(b"x" * 32).decode(), 1767225600,
                     project_id="project")


@pytest.mark.parametrize("now", [1767225299, 1767225901])
def test_past_and_future_replay_timestamps_rejected(now):
    with pytest.raises(WebhookError, match="replay"):
        verify(event(), now)


def test_wrong_project_and_unknown_api_version_fail_closed():
    payload = event()
    payload["data"]["projectId"] = "other"
    with pytest.raises(WebhookError, match="project"):
        verify(payload)
    payload = event()
    payload["apiVersion"] = "2027-01-01"
    with pytest.raises(WebhookError, match="version"):
        verify(payload)


@pytest.mark.parametrize("change", ["outgoing", "group", "email", "attachment", "receipt", "missing_receiver", "extra_member"])
def test_unsupported_events_do_not_register_or_enqueue(change):
    payload = event()
    message = payload["data"]["object"]
    if change == "outgoing":
        message["status"] = "dispatched"
    elif change == "group":
        message["space"]["kind"] = "group"
    elif change == "email":
        message["sentBy"]["handle"] = "person@example.com"
    elif change == "attachment":
        message["content"] = {"type": "attachment"}
    elif change == "receipt":
        payload["type"] = "message.delivered"
    elif change == "missing_receiver":
        del message["receivedBy"]
    else:
        message["space"]["participantIds"].append("another")
    assert verify(payload) is None


def test_authoritative_received_time_is_preserved_on_redelivery():
    payload = event()
    payload["timestamp"] = "2026-01-02T00:00:00Z"
    assert verify(payload).occurred_at == 1767225600


